"""Episode 1's numbers, from real runs of SOEM on the virtual line.

    python3 data.py [runs]      # default 3 runs of each mode; writes data/ep01.json

Mode "frame": joints act when a frame brings new targets (no distributed clock).
Mode "dc":    joints act on SYNC0 from their distributed clocks.
Only the first 0.5 s after OP is skipped (dc: the clocks are still settling; shown separately).
"""
import json, os, statistics as st, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
VW = os.path.join(HERE, '..', '..', 'vwire')
OUT = os.path.join(HERE, 'data')
RUNS = int(sys.argv[1]) if len(sys.argv) > 1 else 3

def run(mode, k):
    tr = os.path.join(OUT, f'{mode}{k}.jsonl')
    subprocess.run([os.path.join(VW, 'build', 'cycle'), 'vwire:chain3', '--' + mode, '--seconds', '3'],
                   env={**os.environ, 'VWIRE_TRACE': tr}, check=True, stdout=subprocess.DEVNULL)
    ev = [json.loads(l) for l in open(tr)]
    t_run = next(e['t_us'] for e in ev if e['ev'] == 'mark' and e['what'].startswith('run'))
    acts = {}
    for e in ev:
        if e['ev'] == 'act' and e['t_us'] > t_run:
            acts.setdefault(e['s'], []).append(e['t_us'])
    n = min(len(v) for v in acts.values())
    def stats(a, b):
        per = [(acts[2][i + 1] - acts[2][i]) * 1000 for i in range(a, b - 1)]
        skew = [(acts[3][i] - acts[2][i]) * 1000 for i in range(a, b)]
        return {'period_mean_ns': st.mean(per), 'period_sd_ns': st.pstdev(per), 'period_min_ns': min(per),
                'period_max_ns': max(per), 'skew_mean_ns': st.mean(skew), 'skew_max_ns': max(abs(x) for x in skew),
                'periods_us': [round(p / 1000, 3) for p in per]}
    os.remove(tr)
    return {'settling': stats(0, 500), 'steady': stats(500, n), 'settled': stats(1000, n), 'cycles': n}

subprocess.run([os.path.join(VW, 'build.sh')], check=True, stdout=subprocess.DEVNULL)
os.makedirs(OUT, exist_ok=True)
res = {m: [run(m, k) for k in range(RUNS)] for m in ('frame', 'dc')}
json.dump(res, open(os.path.join(OUT, 'ep01.json'), 'w'))

# ---- check every property the subtitles state ----
fr, dc = res['frame'], res['dc']
ok = True
def need(cond, what):
    global ok
    print(('ok   ' if cond else 'FAIL ') + what)
    ok &= bool(cond)
need(all(2300 <= r['steady']['cycles'] if False else 2400 <= len(r['steady']['periods_us']) <= 2600 for r in fr), 'about 2,500 cycles measured')
need(all(10e3 <= r['steady']['period_sd_ns'] <= 99e3 for r in fr), 'frame: spread is tens of microseconds, every run')
need(all(r['steady']['period_min_ns'] < 900e3 and r['steady']['period_max_ns'] > 1100e3 for r in fr), 'frame: some cycles hundreds of us early or late')
need(all(r['steady']['period_max_ns'] >= 1200e3 for r in fr), 'frame: a cycle 0.2 ms late exists')
need(all(abs(r['steady']['skew_mean_ns'] - 310) < 1 and r['steady']['skew_max_ns'] < 311 for r in fr), 'frame: J1 to J2 310 ns, every cycle')
need(all(3.5 <= r['steady']['period_sd_ns'] <= 6.5 for r in dc), 'dc: period spread about 5 ns, every run')
need(all(r['settled']['skew_max_ns'] <= 15 for r in dc), 'dc: settled J1/J2 within about 10 ns')
ratio = min(r['steady']['period_sd_ns'] for r in fr) / max(r['steady']['period_sd_ns'] for r in dc)
need(5e3 <= ratio <= 2e4, f'about ten thousand times tighter ({ratio:.0f}x)')

# ---- what the video draws: run 0 of each mode ----
import math
f0, d0 = fr[0], dc[0]
per = f0['steady']['periods_us']
lo, hi, w = 400, 1500, 25
hist = [0] * ((hi - lo) // w)
for p in per:
    i = int((p - lo) // w)
    if 0 <= i < len(hist): hist[i] += 1
dper = [round((p - d0['steady']['period_mean_ns'] / 1000) * 1000, 1) for p in d0['steady']['periods_us']]
dlo, dw = -20, 2
dhist = [0] * 20
for p in dper:
    i = int((p - dlo) // dw)
    if 0 <= i < len(dhist): dhist[i] += 1
D = {
  'frame': {'hist': hist, 'lo': lo, 'w': w, 'sd_us': round(f0['steady']['period_sd_ns'] / 1000, 1),
            'min_us': round(f0['steady']['period_min_ns'] / 1000), 'max_us': round(f0['steady']['period_max_ns'] / 1000),
            'n': len(per), 'out': sum(1 for p in per if p < lo or p >= hi), 'strip': per[:40], 'skew_ns': round(f0['steady']['skew_mean_ns']),
            'sd_all_us': [round(r['steady']['period_sd_ns'] / 1000, 1) for r in fr]},
  'dc': {'hist': dhist, 'lo': dlo, 'w': dw, 'sd_ns': round(d0['steady']['period_sd_ns'], 1),
         'settled_skew_ns': round(max(r['settled']['skew_max_ns'] for r in dc)), 'strip': d0['steady']['periods_us'][:40],
         'sd_all_ns': [round(r['steady']['period_sd_ns'], 1) for r in dc]},
  'ratio': round(ratio),
}
open(os.path.join(HERE, 'ep01_data.js'), 'w').write('// generated by data.py from real runs on vwire:chain3; do not edit\nconst D = ' + json.dumps(D) + ';\n')
if not ok: sys.exit('a stated property failed: fix the script or the run')
for m, rs in res.items():
    for k, r in enumerate(rs):
        s = r['steady']
        print(f"{m} run {k}: period {s['period_mean_ns']/1000:.3f} us  sd {s['period_sd_ns']:.1f} ns  "
              f"min {s['period_min_ns']/1000:.1f} us  max {s['period_max_ns']/1000:.1f} us  "
              f"J1->J2 skew mean {s['skew_mean_ns']:.1f} max {s['skew_max_ns']:.1f} ns"
              f"   (settling: sd {r['settling']['period_sd_ns']:.1f} ns, skew max {r['settling']['skew_max_ns']:.0f} ns)")
